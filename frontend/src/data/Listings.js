export const getListingsByCity = (city) => {
  return listings.filter(listing => listing.city.toLowerCase() === city.toLowerCase());
};

export const getListingById = (id) => {
  return listings.find(listing => listing.id === parseInt(id));
};

export const getAllCities = () => {
  return [...new Set(listings.map(listing => listing.city))];
};